# -*- coding: utf-8 -*-
r"""프로그램 기능 카탈로그 — 팔레트에 블럭으로 놓을 수 있는 '앱 자체 기능'.

왜 필요한가 (2026-07-25):
    사진 삽입·특수문자·양식 채우기 같은 것은 **코드에 박혀 있어** 사용자가 빼거나
    순서를 바꿀 수 없었다. 반면 문자·템플릿·서식 조합 블럭은 전부 사용자 것이다.
    "내가 만들어 넣은 기능도 추가·삭제할 수 있으면 좋겠다"는 요청이 이 간극을
    가리킨다 — 그래서 앱 기능도 **블럭 한 종류**로 만들어 같은 규칙에 태운다.

여기는 '무엇이 있는지'만 정의한다. 실제 실행은 main.py 가 키를 보고 자기
함수로 잇는다(BUILTIN_DISPATCH) — 이 모듈이 UI 를 임포트하지 않게 하려는 것이다.

func_catalog.py 와 헷갈리지 말 것:
    func_catalog = 선택 영역에 **한글 서식**을 먹이는 조작 목록('서식 조합' 블럭)
    builtin_actions = 이 **프로그램의 기능** 자체 (창 열기, 변환 실행 등)
"""

# 분류 — 도구 고르는 창의 왼쪽 목록 (사용자 결정 2026-07-29).
#
# 기준은 **"이 도구가 무엇에 손을 대는가"** 다. 만든 사람 머릿속의 갈래(변환기·
# 삽입기…)가 아니라, 누르기 직전에 사람이 하려는 일로 나눈다:
#   문서 고치기 = 이미 쓴 글에 손을 댄다 (선택 영역이 필요하다)
#   넣기        = 커서 자리에 없던 것을 만들어 넣는다
#   양식        = 문서를 새로 연다
#   관리        = 문서가 아니라 이 프로그램을 만진다
# 갈래를 늘리기 전에 이 문장으로 설명되는지 먼저 볼 것.
#
# 맨 끝의 '미분류'는 **갈래를 안 적은 도구를 받는 그물**이다. 지금은 비어 있고,
# 비어 있는 동안에는 화면에도 안 나온다(by_category 가 빈 갈래를 지운다).
# 나중에 도구를 늘리면서 cat 을 빠뜨려도 그 도구가 목록에서 통째로 사라지지
# 않게 하려는 것이다 — 안 보이는 것이 잘못 분류된 것보다 훨씬 찾기 어렵다.
CATEGORIES = ["문서 고치기", "넣기", "양식", "관리", "미분류"]

# key 는 config.json 에 저장되므로 **바꾸면 기존 블럭이 끊긴다.**
# cat 은 화면에서만 쓰는 값이라 자유롭게 옮겨도 된다.
BUILTIN_ACTIONS = [
    {"key": "convert",      "name": "마크다운 변환",  "cat": "문서 고치기",
     "hint": "선택한 마크다운을 한글 문서로 변환"},
    {"key": "reset_format", "name": "기본 서식",      "cat": "문서 고치기",
     "hint": "선택 영역을 기본 글꼴·크기·줄간격으로 되돌림"},
    {"key": "photo",        "name": "사진",           "cat": "넣기",
     "hint": "그림 파일을 골라 커서 자리에 삽입"},
    # 표기는 '특수기호'로 통일 (사용자 결정 2026-07-25 — 물감 설정의 탭 이름과
    # 같은 말을 쓴다). key 와 저장 데이터는 그대로라 기존 블럭이 자동으로 따라온다.
    {"key": "special",      "name": "특수기호",       "cat": "넣기",
     "hint": "내장 기호 목록 (\\원1\\ \\로마3\\ \\홑낫표\\ …)"},
    {"key": "form_fill",    "name": "양식 채우기",    "cat": "양식",
     "hint": "양식의 빈칸을 뽑아 채운 뒤 새 문서로 열기"},
    {"key": "library",      "name": "라이브러리",     "cat": "관리",
     "hint": "등록한 서식·문자·템플릿·양식 관리"},
    {"key": "search",       "name": "통합 찾기",      "cat": "관리",
     "hint": "블럭과 라이브러리를 한 번에 검색"},
]

ACTION_BY_KEY = {a["key"]: a for a in BUILTIN_ACTIONS}


def by_category():
    """분류 → 그 분류의 도구들. 빈 분류는 내보내지 않는다."""
    out = {}
    for a in BUILTIN_ACTIONS:
        cat = a.get("cat")
        out.setdefault(cat if cat in CATEGORIES else "미분류", []).append(a)
    return {c: out[c] for c in CATEGORIES if c in out}

# 첫 실행 때 '메인' 탭에 깔아 둘 기본 도구. 예전에 코드로 박혀 있던 것들을
# 그대로 옮겨 놓는다 — 처음 쓰는 사람이 빈 화면을 보지 않게 하려는 것이다.
# 그 뒤로는 사용자가 지우든 옮기든 자유이고, 다시 채워 넣지 않는다.
DEFAULT_MAIN_KEYS = ("convert", "reset_format", "photo", "special", "form_fill")

# 마지막 하나는 지울 수 없는 도구 (2026-07-25).
# 변환은 이 프로그램의 본체다. 다른 블럭처럼 옮기고 크기를 바꾸고 이름도
# 고칠 수 있게 하되, **모두 지워 버리면 되살릴 길이 없어** 마지막 하나만 막는다.
# (전역 단축키 Ctrl+Alt+T 는 남지만, 화면에서 사라진 기능을 다시 찾기는 어렵다)
PROTECTED_KEYS = ("convert",)

# 그 블럭이 '마지막 남은 보호 대상'인지 판단할 때 쓸 기본 크기 — 변환은
# 글자가 길어 한 칸으로는 못 읽는다.
DEFAULT_SPANS = {"convert": (3, 2)}      # key → (가로 칸, 세로 줄)


def name_of(key):
    """키 → 사람이 읽는 이름. 모르는 키면 키를 그대로 돌려준다."""
    action = ACTION_BY_KEY.get(key)
    return action["name"] if action else (key or "?")


def hint_of(key):
    action = ACTION_BY_KEY.get(key)
    return action["hint"] if action else ""
